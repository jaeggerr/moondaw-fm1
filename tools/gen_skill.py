HEAD = """<!-- Generated by tools/gen_skill.py from app/fx_help.c and core/song.c.
     Do not edit; run the tool. -->
"""


def probe():
    """The firmware's own answers, {tag: [fields...]}."""
    BUILD.mkdir(exist_ok=True)
    src = BUILD / "skill_probe.c"
    src.write_text(PROBE)
    exe = BUILD / "skill_probe"
    subprocess.run(["cc", "-std=c11", "-O1", "-o", str(exe), str(src),
                    str(ROOT / "core/song.c"), str(ROOT / "core/drum.c"),
                    str(ROOT / "app/fx_help.c")], check=True)
    out = {}
    for line in subprocess.run([str(exe)], check=True, capture_output=True,
                               text=True).stdout.splitlines():
        tag, *rest = line.split("\t")
        out.setdefault(tag, []).append(rest)
    return out


def unmangle(s):
    """Older copies of app/fx_help.c hold moondaw's text read as latin-1 and
    written back as UTF-8 (c_table's unicode_escape, fixed on 01/11/2026): an
    em dash arrived as three characters. Kept so the skill can still be built
    from one. The page itself is ASCII by design -- the panel's font has no
    glyph beyond 126 -- so a dash reads `--` there and here."""
    try:
        return s.encode("latin-1").decode("utf-8")
    except UnicodeError:
        return s


def ticks(lo6, hi6, lo24, hi24):
    """A range, said in ticks where it depends on `ticks`."""
    if (lo6, hi6) == (lo24, hi24):
        return f"`{lo6}`–`{hi6}`" if lo6 != hi6 else f"`{lo6}`"
    at = {"05": "ticks-1", "06": "ticks", "01": "1"}
    return f"`{at.get(lo6, lo6)}`–`{at.get(hi6, hi6)}`"


def step_fx(p):
    pages = {name: unmangle(text) for name, text in p["PAGE"]}
    out = [HEAD, "# The 28 step effects\n",
           "Three to a step, written `f` + the three-letter mnemonic + two hex "
           "digits: `fVOL40`. Never the number — `f0640` is not a thing. An "
           "unknown mnemonic drops the slot.\n",
           "A **setter** is written once and holds until it is written again, "
           "across the loop too, which is why it is worth putting on step `00`. "
           "A **one-shot** dies with its step.\n",
           "The same command twice on one step drops the second, so a cell that "
           "says something and never plays cannot be written. The exception is "
           "`RMP`, which reads the slots to its right: `fVEL20 fRMP1F fVEL7F` is "
           "two `VEL` that are both heard, the first a jump and the second a "
           "swell from it.\n",
           "Ranges below are hexadecimal, as they are written. Where one depends "
           "on the song's `ticks` it says so.\n",
           "| | | | range |", "|---|---|---|---|"]
    for name, desc, kind, ramp, lo6, hi6, lo24, hi24 in p["FX"]:
        r = "written `'MA`" if name == "SYL" else ticks(lo6, hi6, lo24, hi24)
        out.append(f"| [`{name}`](#{name.lower()}) | {desc} | {kind}"
                   f"{', rampable' if ramp == '1' else ''} | {r} |")
    out.append("")
    for name, desc, kind, ramp, lo6, hi6, lo24, hi24 in p["FX"]:
        out += [f"## {name}", "", f"*{desc}* — a {kind}"
                f"{', and `RMP` can ramp it' if ramp == '1' else ''}, "
                + ("its value an entry of the song's syllable table."
                   if name == "SYL" else f"{ticks(lo6, hi6, lo24, hi24)}."), ""]
        if name == "SYL":
            out += ["This is the one effect whose value is text, and it is the "
                    "one never written as `f`: the token is a straight "
                    "apostrophe and the phonemes, `'MA`. An `fSYL40` is dropped "
                    "on the way in — the number means nothing outside the "
                    "song's own table.", ""]
        text = pages.get(name, "")
        out += ["\n".join(line for line in text.replace("\\n", "\n").split("\n") if line), ""]
    return "\n".join(out)


def limits(p):
    d = {k: v for k, *v in p["DEF"]}
    L = {k: v[0] for k, *v in p["LIM"]}
    tr, bl = L["tracks"], L["blocks"]
    out = ["", "### What the machine holds", "",
           f"| | |", "|---|---|",
           f"| tracks | {tr}, written `t0`–`t{int(tr) - 1}` |",
           f"| blocks a track | {bl}, `00`–`{int(bl) - 1:02X}` |",
           f"| steps a block | {L['steps']}, rows `00`–`{int(L['steps']) - 1:02X}` |",
           f"| steps in the whole song | {L['pool']}, from one pool |",
           f"| notes a step | {L['notes']} |",
           f"| effects a step | {L['fx']} |",
           f"| instruments | {L['instr']}, `i00`–`i{int(L['instr']) - 1:02X}`, "
           f"{L['layers']} layers each |",
           f"| phrases | {L['phrases']}, `arr 00`–`arr {int(L['phrases']) - 1:02X}` |",
           f"| steps a phrase may be held for | {L['cycle']} |",
           f"| sample slots | {L['samples']}, and {L['zones']} zones |",
           f"| syllables | {L['syllables']} distinct, {L['syllen']} characters each |",
           f"| names | {L['instname']} characters an instrument, "
           f"{L['name']} a phrase or a section |", "",
           "A step nobody wrote costs nothing: the pool is shared, so an empty "
           "block and the bars of silence inside a long one are free. What costs "
           "is steps actually written, and they are counted for the whole song.",
           "", "### Ranges, and what a field is when the file leaves it out", "",
           "| field | range | left out |", "|---|---|---|",
           f"| `bpm` | {L['bpmrange'].replace(' ', '–')} | {d['bpm'][0]} |",
           f"| `ticks` | 1–{L['ticksmax']} | {d['ticks'][0]} |",
           f"| `meter` | 1–{L['metermax']} each | {d['meter'][0]} |",
           f"| `tracks` | 1–16, cut to {tr} | {d['tracks'][0]} |",
           f"| `swing` | {L['swingrange'].replace(' ', '–')} | {d['swing'][0]} |",
           f"| `reverb` | 0–127 both | {d['reverb'][0]} |",
           f"| `delay` | 0–96, 0–127 | {d['delay'][0]} |",
           f"| `trk` | vol 0–127, pan -64–63, rev/ech 0–127 | {d['trk'][0]} |",
           f"| `len` | 1–{L['steps']} | {d['len'][0]} |",
           f"| a note | {L['noterange'].replace(' ', '–')} as MIDI, so `C-4` is "
           "middle C and `A-4` is 440 Hz | nothing on that step |",
           f"| `gain`, `level` | {L['gain'].replace(' ', ' to ')} dB | 0 |",
           f"| `tract` | {L['tract'].replace(' ', '–')} percent | 100 |",
           f"| `tune` of a zone | ±{L['tune']} cents | 0 |", "",
           "An `inst` line puts the whole slot back to neutral before it reads "
           "what the line names: what a line leaves out is the ground, never the "
           "slot's last tenant. The ground is",
           "", f"    inst NN {d['inst'][0]}", "",
           "### The engines", "", "| engine | timbre |", "|---|---|"]
    for name, tmax in p["ENG"]:
        out.append(f"| `{name}` | 0–{tmax} |")
    out += ["", "### The instruments a song gets for free", "",
            "These slots already hold a sound, so a song can play without one "
            "`inst` line of its own. They come back written out in full when the "
            "machine saves.", "", "| slot | | engine |", "|---|---|---|"]
    for idx, name, eng, tim in p["PRE"]:
        out.append(f"| `i{idx}` | {name} | `{eng}` timbre {tim} |")
    out.append("")
    return "\n".join(out)


def gestures(_):
    """Every screen's gestures, from app/help.c -- the help the panel itself
    shows, so the skill cannot teach a button the machine does not have."""
    src = (ROOT / "app/help.c").read_text()
    out = ["", "What each screen answers, as HELP on the device says it. The "
           "words are the machine's own.", ""]
    for name in re.findall(r"static const Item (\w+)_items\[\]", src):
        body = src[src.index(f"{name}_items[] = {{"):]
        body = body[:body.index("\n};")]
        rows = re.findall(r'\{ "([^"]*)", "([^"]*)" \}', body)
        out += [f"### {'GESTURES' if name == 'gestures' else name.upper()}", "",
                "| | |", "|---|---|"]
        out += [f"| `{k}` | {v} |" for k, v in rows]
        out.append("")
    return "\n".join(out)


def drums(p):
    out = ["", "### The kits, and the pieces each one has", "",
           "`timbre` picks the kit. A kit has 8 pieces, or 11 for Felucca's own "
           "two, and the note picks the piece. The note beside each piece is "
           "where it sounds as it was designed; the rest of the map is those "
           "same pieces retuned.", "", "| timbre | kit | pieces |", "|---|---|---|"]
    for idx, name, pieces in p["KIT"]:
        out.append(f"| {idx} | `{name}` | {pieces} |")
    out += ["", "### The map", "",
            "The General MIDI convention, notes `B-1` to `A-5`. A note outside "
            "it plays its pitch class of `C-2`–`B-2`, so nothing is ever "
            "silent.", "", "| note | | note | | note | |", "|---|---|---|---|---|---|"]
    rows = p["GM"]
    third = (len(rows) + 2) // 3
    for i in range(third):
        cells = []
        for col in range(3):
            k = i + col * third
            cells += [f"`{rows[k][0]}`", rows[k][1]] if k < len(rows) else ["", ""]
        out.append("| " + " | ".join(cells) + " |")
    out += ["", "`BD` kick, `SD` snare, `RS` rim, `CP` clap, `CH` closed hat, "
            "`OH` open hat, `TM` tom, `CY` cymbal, `CB` bell, `CG` conga, `CL` "
            "clave.", "",
            "Each piece of a track is one lane, and a lane is mono: a hit cuts "
            "that lane's last hit, so a retuned tom cuts the tom before it, and "
            "a closed hat chokes the open one. Different pieces ring together.",
            ""]
    return "\n".join(out)


def splice(text, tag, block):
    a = text.index(f"<!-- GEN:{tag} -->") + len(f"<!-- GEN:{tag} -->")
    b = text.index("<!-- /GEN -->", a)
    return text[:a] + block + text[b:]


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="write nothing; 1 if out of date")
    a = ap.parse_args()

    p = probe()
    want = {SKILL / "step-fx.md": step_fx(p)}
    for name, tag, block in (("format.md", "limits", limits(p)),
                             ("engines.md", "drums", drums(p)),
                             ("control.md", "gestures", gestures(p))):
        f = SKILL / name
        if f.exists():
            want[f] = splice(f.read_text(), tag, block)

    stale = [f for f, text in want.items() if not f.exists() or f.read_text() != text]
    if a.check:
        for f in stale:
            print(f"{f.relative_to(ROOT)}: out of date (python3 tools/gen_skill.py)")
        return 1 if stale else 0
    for f, text in want.items():
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(text)
    print(f"{len(want)} files, {len(stale)} rewritten: " +
          ", ".join(str(f.relative_to(ROOT)) for f in want))
    return 0


if __name__ == "__main__":
    sys.exit(main())
