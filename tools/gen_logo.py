#!/usr/bin/env python3
"""app/logo.h: the MOONDAW wordmark, from the Mac app's own generator.

The logo is pixel art -- two lines of blocky letters, the O's of MOON drawn
as crescents -- so it goes on the panel as pixels, not as a picture: the
grid is 66 x 40, two bits a pixel (nothing / gold / cyan), 660 bytes, and
app/splash.c blows it up by an integer factor with hard edges, which is how
the generator means it to be scaled.

Its two inks are already the FM-1's: GOLD is C_FX and CYAN is C_TITLE, the
same values in both repositories (they were lifted from moondaw's src/ui/ui.c,
which is also where theme.h got them).

    MOONDAW=../moondaw python3 tools/gen_logo.py > app/logo.h

Needs moondaw's checkout and Pillow; the header is committed, so a build
never does.
"""

import os
import sys

MOONDAW = os.environ.get("MOONDAW", "../moondaw")
sys.path.insert(0, os.path.join(MOONDAW, "tools", "mkicon"))
import mkicon  # noqa: E402

INK = {mkicon.GOLD: 1, mkicon.CYAN: 2}

grid = mkicon.render_grid()
w, h = grid.size
px = grid.load()

cells = []
for y in range(h):
    for x in range(w):
        r, g, b, a = px[x, y]
        cells.append(INK[(r, g, b)] if a else 0)

packed = []
for i in range(0, len(cells), 4):
    v = 0
    for j, c in enumerate(cells[i:i + 4]):
        v |= c << (2 * j)        # the leftmost pixel in the lowest bits
    packed.append(v)

out = sys.stdout.write
out("/* SPDX-License-Identifier: GPL-3.0-only */\n")
out("/* GENERATED by tools/gen_logo.py from moondaw's tools/mkicon -- do not edit.\n"
    " * The app icon's wordmark, %d x %d, two bits a pixel: 0 nothing, 1 C_FX\n"
    " * (gold), 2 C_TITLE (cyan). Four pixels a byte, leftmost in the lowest\n"
    " * bits, rows top to bottom. */\n" % (w, h))
out("#ifndef LOGO_H\n#define LOGO_H\n#include <stdint.h>\n\n")
out("#define LOGO_COLS %d\n#define LOGO_ROWS %d\n\n" % (w, h))
out("static const uint8_t logo_px[%d] = {\n" % len(packed))
for i in range(0, len(packed), 16):
    out("    " + ",".join("%3d" % v for v in packed[i:i + 16]) + ",\n")
out("};\n\n#endif\n")
