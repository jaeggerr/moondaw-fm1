"""Bakes the interface's type into app/fonts.h: antialiased glyphs, 4 bits of coverage a pixel.

  tools/gen_fonts.py > app/fonts.h        (needs Pillow; the header is committed, so a build does not)
  tools/gen_fonts.py --specimen > app/fonts_spec.h   (the sizes app/type.c lays side by side)

The faces are the app's -- Barlow Condensed for what is read as a word, JetBrains Mono for what is
read as a number -- at the sizes proto/pattern.html settled on for a 240 x 240 panel. Both are under
the SIL Open Font License (LICENSES/). ASCII 32..126, plus the single guillemet of a back label as 127.
"""
import sys

from PIL import Image, ImageDraw, ImageFont

D = "assets/fonts/"
# The condensed face is antialiased. The mono face is NOT: at these sizes smoothing turns its
# strokes to grey fog (LEN read as LBI at 7 px), while the hinted one-bit rendering at 8 px is
# crisp -- tried side by side on 10/10. So "1" below: whole pixels, placed by the font's own hints.
FONTS = [  # name, file, variation, size in pixels, mode
    ("F_COND14", "BarlowCondensed-Bold.ttf", None, 14, "L"),
    ("F_COND12", "BarlowCondensed-Bold.ttf", None, 12, "L"),
    ("F_COND11", "BarlowCondensed-Bold.ttf", None, 11, "L"),
    ("F_COND9", "BarlowCondensed-Bold.ttf", None, 9, "L"),
    ("F_MONO8", "JetBrainsMono[wght].ttf", 500, 8, "1"),
]
# The specimen: each face and rendering at the sizes worth weighing on the panel itself (28/10:
# the screens above, seen on the FM-1, were too small to read). The last field is its page title.
SPECIMEN = [
    *[(f"F_MONO1_{s}", "JetBrainsMono[wght].ttf", 500, s, "1", f"MONO 1-BIT {s}") for s in (8, 9, 10, 11, 12, 14, 16)],
    *[(f"F_MONOA_{s}", "JetBrainsMono[wght].ttf", 600, s, "L", f"MONO SMOOTH {s}") for s in (10, 12, 14, 16)],
    *[(f"F_COND_{s}", "BarlowCondensed-Bold.ttf", None, s, "L", f"CONDENSED {s}") for s in (11, 12, 14, 16, 18, 20)],
]
specimen = "--specimen" in sys.argv[1:]
if specimen:
    FONTS = [f[:5] for f in SPECIMEN]
CHARS = [chr(c) for c in range(32, 127)] + ["‹"]

print("/* SPDX-License-Identifier: GPL-3.0-only */")
print("/* GENERATED by tools/gen_fonts.py -- do not edit.")
print(" * Barlow Condensed and JetBrains Mono, SIL Open Font License 1.1 (LICENSES/). */")
guard = "FONTS_SPEC_H" if specimen else "FONTS_H"
print(f"#ifndef {guard}\n#define {guard}\n#include <stdint.h>\n")
print("typedef struct { uint16_t at; uint8_t w, h, adv; int8_t x, y; } Glyph;")
print("typedef struct { uint8_t ascent, height; const Glyph *g; const uint8_t *px; } Font;\n")
names = []
for name, file, wght, size, mode in FONTS:
    f = ImageFont.truetype(D + file, size)
    if wght:
        f.set_variation_by_axes([wght])
    ascent, descent = f.getmetrics()
    glyphs, data = [], []
    for ch in CHARS:
        adv = round(f.getlength(ch))
        box = f.getbbox(ch, mode=mode)  # relative to the origin at (0, ascent line top)
        w, h = (box[2] - box[0], box[3] - box[1]) if box else (0, 0)
        if w <= 0 or h <= 0:
            glyphs.append((len(data), 0, 0, adv, 0, 0))
            continue
        im = Image.new("L", (w, h), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = mode
        d.text((-box[0], -box[1]), ch, font=f, fill=255)
        nib = [(p + 8) // 17 for p in im.tobytes()]
        at = len(data)
        for i in range(0, len(nib), 2):
            data.append(nib[i] << 4 | (nib[i + 1] if i + 1 < len(nib) else 0))
        glyphs.append((at, w, h, adv, box[0], box[1]))
    low = name.lower()
    print(f"static const uint8_t {low}_px[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        print("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    print("};")
    print(f"static const Glyph {low}_g[{len(glyphs)}] = {{")
    for g in glyphs:
        print("    {%d,%d,%d,%d,%d,%d}," % g)
    print("};")
    names.append((name, low, ascent, ascent + descent))
print("\nstatic const Font FONTS[] = {")
for name, low, a, h in names:
    print(f"    {{ {a}, {h}, {low}_g, {low}_px }},")
print("};")
print("enum { " + ", ".join(n for n, *_ in names) + " };")
if specimen:
    print("static const char *const FONT_NAMES[] = { " + ", ".join(f'"{f[5]}"' for f in SPECIMEN) + " };")
print("\n#endif")
