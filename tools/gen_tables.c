/* Writes core/tables.h: every curve the engine needs, worked out once on
 * a machine that has a libm so the FM-1 never needs one. The formulas
 * are moondaw's (instruments/notes.c, wave.c, chain.c), in float where
 * moondaw is in float, so the numbers are the ones it computes.
 *
 *   cc tools/gen_tables.c -lm -o build/gen_tables && build/gen_tables > core/tables.h */
#include <math.h>
#include <stdio.h>

#define FS 44100.0

static void open(const char *type, const char *name, int n)
{
    printf("\nstatic const %s %s[%d] = {", type, name, n);
}

int main(void)
{
    printf("/* SPDX-License-Identifier: GPL-3.0-only */\n"
           "/* GENERATED by tools/gen_tables.c -- do not edit. */\n"
           "#ifndef TABLES_H\n#define TABLES_H\n#include <stdint.h>\n");

    /* One octave of periods at a 4 MHz clock, a cent apart, from note 0
     * (8.18 Hz). Q12. The octaves above are shifts. */
    open("uint32_t", "PERIOD_Q12", 1200);
    for (int c = 0; c < 1200; c++) {
        double hz = 440.0 * pow(2.0, (c - 6900) / 1200.0);
        printf("%s%.0f,", c % 8 ? " " : "\n    ", floor(4000000.0 / hz * 4096.0 + 0.5));
    }
    printf("\n};\n");

    /* dB -> linear, -64..+24, Q16. chain_db_to_gain. */
    open("uint32_t", "DB_GAIN_Q16", 89);
    for (int db = -64; db <= 24; db++)
        printf("%s%.0f,", (db + 64) % 8 ? " " : "\n    ",
               db == 0 ? 65536.0 : floor(exp2f((float)db / 6.0205999f) * 65536.0 + 0.5));
    printf("\n};\n");

    /* tan(pi f / FS) for the filter, f = 30 Hz * 2^(9.06 x), x = i/1024,
     * capped at 0.45 FS. Q20. */
    open("uint32_t", "SVF_G_Q20", 1025);
    for (int i = 0; i <= 1024; i++) {
        float hz = 30.0f * exp2f((float)i / 1024.0f * 9.06f);
        if (hz > (float)FS * 0.45f)
            hz = (float)FS * 0.45f;
        printf("%s%.0f,", i % 8 ? " " : "\n    ",
               floor(tanf(3.14159265f * hz / (float)FS) * 1048576.0 + 0.5));
    }
    printf("\n};\n");

    /* CRS: levels per polarity and their inverse; RAT: samples held. Q8. */
    open("uint32_t", "CRUSH_LEVELS_Q8", 256);
    for (int i = 0; i < 256; i++)
        printf("%s%.0f,", i % 8 ? " " : "\n    ",
               floor(exp2f(12.0f - (float)i * (10.5f / 255.0f) - 1.0f) * 256.0 + 0.5));
    printf("\n};\n");
    open("uint32_t", "CRUSH_STEP_Q8", 256);
    for (int i = 0; i < 256; i++)
        printf("%s%.0f,", i % 8 ? " " : "\n    ",
               floor(32768.0 / exp2f(12.0f - (float)i * (10.5f / 255.0f) - 1.0f) * 256.0 + 0.5));
    printf("\n};\n");
    open("uint32_t", "CRUSH_HOLD_Q8", 256);
    for (int i = 0; i < 256; i++)
        printf("%s%.0f,", i % 8 ? " " : "\n    ",
               i == 0 ? 0.0 : floor(exp2f((float)i * (6.0f / 255.0f)) * 256.0 + 0.5));
    printf("\n};\n");

    /* The reverb: eight delay lines, their lengths at 44.1 kHz; for each
     * size 0..127 the gain that makes a line decay 60 dB in the room's
     * time (250 ms to 5 s), the Hadamard normalisation folded in, Q16;
     * for each damping 0..127 the one-pole coefficient (16 kHz down to
     * 1 kHz), Q15. reverb.c reverb_set. */
    {
        static const int base[8] = { 1117, 1259, 1381, 1543, 1721, 1867, 2053, 2311 };
        printf("\nstatic const uint16_t REVERB_FB_Q16[128][8] = {");
        for (int size = 0; size < 128; size++) {
            float rt = (float)(int)(250.0f * exp2f((float)size / 127.0f * 4.32f)) / 1000.0f;
            printf("\n    {");
            for (int k = 0; k < 8; k++) {
                float t = (float)(base[k] * 44100 / 48000) / 44100.0f;
                printf(" %.0f,", floor(powf(10.0f, -3.0f * t / rt) * 0.35355339f * 65536.0 + 0.5));
            }
            printf(" },");
        }
        printf("\n};\n");
        open("uint16_t", "REVERB_DAMP_Q15", 128);
        for (int d = 0; d < 128; d++) {
            float fc = (float)(int)(16000.0f * exp2f(-(float)d / 127.0f * 4.0f));
            if (fc > (float)FS * 0.45f)
                fc = (float)FS * 0.45f;
            printf("%s%.0f,", d % 8 ? " " : "\n    ", floor(expf(-6.2831853f * fc / (float)FS) * 32768.0 + 0.5));
        }
        printf("\n};\n");
    }

    open("int16_t", "SINE_Q15", 257);
    for (int i = 0; i <= 256; i++)
        printf("%s%.0f,", i % 8 ? " " : "\n    ",
               floor(sin(i * 2.0 * M_PI / 256.0) * 32767.0 + 0.5));
    printf("\n};\n");

    /* The five shapes of the wave engine, 32 steps each: saw, triangle,
     * sine, half-rectified sine, full-rectified sine. wave.c build_table. */
    printf("\nstatic const int16_t WAVE_SHAPES[5][32] = {");
    for (int shape = 0; shape < 5; shape++) {
        printf("\n    {");
        for (int i = 0; i < 32; i++) {
            float x = (float)i / 32.0f, v, s = sinf(6.2831853f * x);
            switch (shape) {
            case 1: v = x < 0.5f ? (4.0f * x - 1.0f) : (3.0f - 4.0f * x); break;
            case 2: v = s; break;
            case 3: v = s > 0.0f ? 2.0f * s - 1.0f : -1.0f; break;
            case 4: v = 2.0f * fabsf(s) - 1.0f; break;
            default: v = 1.0f - 2.0f * x; break;
            }
            printf("%s%d,", i % 8 ? " " : "\n        ", (short)(v * 16000.0f));
        }
        printf("\n    },");
    }
    printf("\n};\n\n#endif\n");
    return 0;
}
