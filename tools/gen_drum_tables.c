/* Writes core/drum_tables.h: the tables of Felucca's drum voices
 * (core/drum_voice.c), worked out as Felucca-Engines' own generator
 * (tools/gen_engine_tables.py, MIT) works them out, at 44.1 kHz:
 * SINE, PITCH_OCT and pitch_inc(), SVF_G, TANH_Q15.
 *
 *   cc tools/gen_drum_tables.c -lm -o build/gen_drum_tables && build/gen_drum_tables > core/drum_tables.h */
#include <math.h>
#include <stdio.h>

#define FS 44100
#define CTL 32

static void row(int i, int per)
{
    printf(i % per ? " " : "\n    ");
}

int main(void)
{
    static long long inc[2048];

    printf("/* SPDX-License-Identifier: MIT */\n"
           "/* GENERATED by tools/gen_drum_tables.c -- do not edit. The tables of\n"
           " * Felucca-Engines (tools/gen_engine_tables.py, MIT, Copyright (C) 2026 Leo\n"
           " * Kuroshita, Hugelton Instruments), for its drum voices, at 44.1 kHz. */\n"
           "#ifndef DRUM_TABLES_H\n#define DRUM_TABLES_H\n#include <stdint.h>\n"
           "#define FS %d\n#define CTL %d\n", FS, CTL);

    /* 1025 points: SINE[i + 1] needs no wrap */
    printf("\nstatic const int16_t SINE[1025] = {");
    for (int i = 0; i < 1025; i++) {
        row(i, 12);
        printf("%d,", (int)lround(32767 * sin(2 * M_PI * i / 1024)));
    }
    printf("\n};\n");

    /* the phase increment of pitch p in 1/16 semitone, kept as its top octave */
    for (int p = 0; p < 2048; p++) {
        double f = 440.0 * pow(2.0, (p / 16.0 - 69) / 12);
        long long v = (long long)(f / FS * 4294967296.0);
        inc[p] = v > 0x7FFFFFFF ? 0x7FFFFFFF : v;
    }
    for (int q = 0; q < 2048; q++)
        if (inc[q] != inc[1856 + (q + 64) % 192] >> (10 - (q + 64) / 192)) {
            fprintf(stderr, "gen_drum_tables: pitch %d is not its octave's\n", q);
            return 1;
        }
    printf("\nstatic const uint32_t PITCH_OCT[192] = {");
    for (int i = 0; i < 192; i++) {
        row(i, 8);
        printf("%lld,", inc[1856 + i]);
    }
    printf("\n};\n"
           "/* phase increment of pitch p in 1/16 semitone, 0..2047 (MIDI 0..127) */\n"
           "static inline uint32_t pitch_inc(uint32_t p)\n"
           "{\n"
           "    uint32_t i = p + 64u, o = (i * 21846u) >> 22;\n"
           "    return PITCH_OCT[i - o * 192u] >> (10u - o);\n"
           "}\n");

    /* tan(pi fc / FS), Q12, for the cutoffs 30 Hz .. 16 kHz of 0..127 */
    printf("\nstatic const uint16_t SVF_G[128] = {");
    for (int v = 0; v < 128; v++) {
        double f = 30.0 * pow(16000.0 / 30, v / 127.0);
        if (f > 0.45 * FS)
            f = 0.45 * FS;
        row(v, 12);
        printf("%d,", (int)(4096 * tan(M_PI * f / FS)));
    }
    printf("\n};\n");

    /* tanh for |x| in 0..2 (Q12 in, Q15 out) */
    printf("\nstatic const int16_t TANH_Q15[257] = {");
    for (int i = 0; i < 257; i++) {
        row(i, 12);
        printf("%d,", (int)(32767 * tanh(i / 256.0 * 2)));
    }
    printf("\n};\n\n#endif\n");
    return 0;
}
